-- מיגרציה של קטגוריות קיימות בקטלוג האישי (טבלת products) מהתפריט הישן
-- לתפריט החדש המבוסס על הקטגוריות האמיתיות באתר רמי לוי (ר' static/constants.js
-- ו-scripts/categorize.py). בלי זה, מוצרים שכבר נוספו עם קטגוריה ישנה לא
-- יופיעו ברשימה כי הקטגוריה שלהם לא קיימת יותר ב-CATEGORY_ORDER.
update products set category = case category
  when 'ירקות ופירות' then 'פירות ירקות ופיצוחים'
  when 'מוצרי חלב' then 'חלב ביצים וגבינות'
  when 'דגים ובשר' then 'בשר עוף ודגים'
  when 'לחם ומאפים' then 'לחם ומאפים טריים'
  when 'קפואים' then 'קפוא ומצונן'
  when 'שימורים' then 'מזווה ושימורים'
  when 'שתייה' then 'משקאות ואלכוהול'
  when 'פיצוחים וחטיפים' then 'חטיפים ומתוקים'
  when 'מוצרי ניקיון' then 'אחזקת הבית ובעלי חיים'
  when 'טואלטיקה' then 'פארם ותינוקות'
  when 'מוצרי תינוקות' then 'פארם ותינוקות'
  when 'מזווה' then 'מזווה ושימורים'
  else category
end;
